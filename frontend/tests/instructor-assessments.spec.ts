import { expect, test } from '@playwright/test'

test('reusable code assessment becomes a fixed assignment with a reviewable learner response', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/instructor/assessments')
  await page.getByRole('tab', { name: 'Code' }).click()
  await page.getByLabel('Title').fill('Bell pair code review')
  await page.getByLabel('Study instructions').fill('Study the Bell circuit, then write the equivalent code and explain it.')
  await page.getByLabel('Starter code (optional)').fill('# Prepare two qubits')
  await page.getByLabel('Prompt', { exact: true }).fill('Which gate creates the initial superposition?')
  await page.getByRole('textbox', { name: 'Answer 1' }).fill('Hadamard')
  await page.getByRole('textbox', { name: 'Answer 2' }).fill('Pauli X')
  await page.getByRole('textbox', { name: 'Answer 3' }).fill('Measurement')
  await page.getByRole('textbox', { name: 'Answer 4' }).fill('SWAP')
  await page.getByLabel('Explanation').fill('H on q0 creates the initial superposition.')
  await page.getByLabel('Written response prompt').fill('Why do the outcomes correlate?')
  await page.getByRole('button', { name: 'Preview learner view' }).click()
  await expect(page.getByLabel('Learner preview')).toContainText('Bell pair code review')
  await page.getByRole('button', { name: 'Save reusable assessment' }).click()
  await expect(page.getByRole('status')).toContainText('Reusable assessment saved')
  await page.getByRole('link', { name: 'Use in assignment' }).first().click()
  await expect(page.getByLabel('Title')).toHaveValue('Bell pair code review')
  await expect(page.getByLabel('Exercise type')).toHaveValue('code')
  await expect(page.getByLabel('Starter code (optional)')).toHaveValue('# Prepare two qubits')
  await page.getByRole('button', { name: 'Publish assignment' }).click()
  await expect(page.getByRole('status')).toContainText('Assignment published')
  const reviewHref = await page.getByRole('link', { name: 'Review' }).getAttribute('href')

  await page.goto('/login')
  await page.getByLabel('Email').fill('coder@example.edu')
  await page.getByLabel('Password', { exact: true }).fill('demo-pass-123')
  await page.getByRole('button', { name: 'Log in', exact: true }).last().click()
  await expect(page).toHaveURL(/\/home$/)
  await page.goto('/assignments')
  await page.getByRole('link', { name: /Bell pair code review/ }).click()
  await page.getByLabel('Code response').fill('h(0)\ncnot(0, 1)')
  await page.getByRole('radio', { name: 'Hadamard' }).check()
  await page.getByLabel('Written response').fill('H branches q0 and CNOT correlates q1.')
  await page.getByRole('button', { name: 'Save response draft' }).click()
  await page.reload()
  await expect(page.getByLabel('Code response')).toHaveValue('h(0)\ncnot(0, 1)')
  await page.getByRole('button', { name: 'Submit response' }).click()
  await expect(page.getByRole('status')).toContainText('Response submitted')
  await expect(page.getByText('h(0)\ncnot(0, 1)')).toBeVisible()
  const pendingAttempt = await page.evaluate(() => JSON.parse(localStorage.getItem('learner-progress-storage') ?? '{}').state.assessmentAttempts.find((item: { kind: string }) => item.kind === 'assignment'))
  expect(pendingAttempt).toMatchObject({ kind: 'assignment', status: 'pending', passed: null })
  expect(pendingAttempt.snapshot.code).toBe('h(0)\ncnot(0, 1)')
  await page.goto(reviewHref!)
  await expect(page.getByText('Code response · not executed')).toBeVisible()
  await expect(page.getByText('h(0)\ncnot(0, 1)')).toBeVisible()
  await page.getByLabel('Instructor feedback').fill('Good circuit translation. Explain the measurement step next.')
  await page.getByRole('button', { name: 'Save feedback' }).click()
  await expect(page.getByRole('status')).toContainText('Visible to this learner')
  const reviewedAttempt = await page.evaluate(() => JSON.parse(localStorage.getItem('learner-progress-storage') ?? '{}').state.assessmentAttempts.find((item: { kind: string }) => item.kind === 'assignment'))
  expect(reviewedAttempt.status).toBe('graded')
  expect(reviewedAttempt.feedback).toContain('Good circuit translation. Explain the measurement step next.')
})

test('instructor curriculum previews the learner content and review status', async ({ page }) => {
  await page.goto('/instructor/curriculum')
  await expect(page.getByRole('heading', { name: 'Curriculum review' })).toBeVisible()
  await expect(page.getByText('Faculty review pending').first()).toBeVisible()
  await page.getByRole('navigation', { name: 'Curriculum units' }).getByRole('button', { name: /Gates and Circuits/ }).click()
  await expect(page.getByRole('heading', { name: 'Gates and Circuits' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Preview learner unit' })).toHaveAttribute('href', '/curriculum/u2')
  await expect(page.getByRole('link', { name: 'Open learner lesson' })).toHaveAttribute('href', /\/curriculum\/u2\//)
})
