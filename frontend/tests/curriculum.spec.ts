import { expect, test } from '@playwright/test'

test('learner follows the beginner path, resumes, and retries a unit quiz', async ({ page }) => {
  await page.goto('/curriculum')
  await expect(page.getByRole('heading', { name: 'Curriculum', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Start the learning path' })).toHaveAttribute('href', '/curriculum/u1/u1-quantum-foundations')
  await page.getByRole('link', { name: 'Start the learning path' }).click()

  await expect(page).toHaveURL(/\/curriculum\/u1\/u1-quantum-foundations$/)
  await expect(page.getByRole('heading', { name: 'Quantum Foundations' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Breadcrumb' })).toBeVisible()
  const complete = page.getByRole('button', { name: /Complete lesson · \+10 XP/ })
  await expect(complete).toBeDisabled()
  await page.getByRole('radio', { name: 'Two complex amplitudes whose squared magnitudes sum to 1' }).check()
  await page.getByRole('radio', { name: 'One sampled outcome, not every amplitude' }).check()
  await expect(complete).toBeEnabled()
  await complete.click()
  await expect(page.getByText('Lesson complete. Your XP was awarded once.')).toBeVisible()
  await page.getByRole('link', { name: 'Next: Qubits and measurement' }).click()
  await expect(page.getByRole('heading', { name: 'Qubits and measurement' })).toBeVisible()

  await page.goto('/curriculum')
  await expect(page.getByRole('link', { name: 'Resume your last lesson' })).toHaveAttribute('href', '/curriculum/u1/u1-qubits-and-measurement')
  await page.getByRole('link', { name: 'Resume your last lesson' }).click()
  await page.getByRole('navigation', { name: 'Breadcrumb' }).getByRole('link', { name: 'Quantum Foundations' }).click()
  await page.getByRole('link', { name: 'Take unit quiz' }).click()

  await page.getByRole('button', { name: 'Submit quiz' }).click()
  await expect(page.getByText('Answer all 3 questions before submitting.', { exact: true })).toBeVisible()
  await page.getByRole('radio', { name: '|β|²', exact: true }).check()
  await page.getByRole('radio', { name: '1/2', exact: true }).check()
  await page.getByRole('radio', { name: 'A global phase on the whole state' }).check()
  await page.getByRole('button', { name: 'Submit quiz' }).click()
  await expect(page.getByText('3/3 correct · 100%')).toBeVisible()
  await page.getByRole('button', { name: 'Retry quiz' }).click()
  await page.getByRole('radio', { name: 'β', exact: true }).check()
  await page.getByRole('radio', { name: '1/2', exact: true }).check()
  await page.getByRole('radio', { name: 'A global phase on the whole state' }).check()
  await page.getByRole('button', { name: 'Submit quiz' }).click()
  await expect(page.getByText('2/3 correct · 67%')).toBeVisible()
  await expect(page.getByText('Best score: 100%')).toBeVisible()
  await expect(page.getByText('2 attempts')).toBeVisible()
  await expect(page.getByText('· passed')).toBeVisible()
  const quizHistory = await page.evaluate(() => JSON.parse(localStorage.getItem('learner-progress-storage') ?? '{}').state.assessmentAttempts.filter((item: { kind: string }) => item.kind === 'unit-quiz'))
  expect(quizHistory.map((item: { score: number }) => item.score)).toEqual([100, 67])
  expect(Object.keys(quizHistory[0].snapshot.answers)).toHaveLength(3)
  await page.reload()
  await expect(page.getByText('Best score: 100%')).toBeVisible()
})
