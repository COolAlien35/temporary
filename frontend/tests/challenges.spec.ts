import { expect, test } from '@playwright/test'

test('challenge grading rejects an empty circuit, records review, and allows a passing retry', async ({ page }) => {
  await page.goto('/challenges')
  await expect(page.getByRole('heading', { name: 'Build, run, prove it.' })).toBeVisible()
  await page.getByRole('link', { name: 'Solve →' }).first().click()
  await expect(page.getByRole('heading', { name: 'Make a balanced qubit' })).toBeVisible()
  await page.getByRole('button', { name: 'Submit attempt' }).click()
  await expect(page).toHaveURL(/\/challenges\/balanced-qubit\/attempts\//)
  await expect(page.getByText('Keep practicing')).toBeVisible()
  await expect(page.getByText(/CHECK: Distribution is .* away from target/)).toBeVisible()
  await page.getByRole('link', { name: 'Retry challenge' }).click()
  await page.getByRole('button', { name: 'H', exact: true }).click()
  await page.getByRole('button', { name: 'Submit attempt' }).click()
  await expect(page).toHaveURL(/\/challenges\/balanced-qubit\/attempts\//)
  await expect(page.getByText('Passed')).toBeVisible()
  await expect(page.getByText('PASS: Target measurement distribution reached')).toBeVisible()
  await expect(page.getByText('H · q0')).toBeVisible()
  const recorded = await page.evaluate(() => JSON.parse(localStorage.getItem('learner-progress-storage') ?? '{}').state.assessmentAttempts)
  expect(recorded.filter((item: { kind: string }) => item.kind === 'circuit-challenge')).toHaveLength(2)
  expect(recorded[1].snapshot.circuit.gates[0].type).toBe('H')
  await page.reload()
  await expect(page.getByText('Passed')).toBeVisible()
  await page.getByRole('link', { name: 'Back to challenge' }).click()
  await expect(page.getByText('2 submitted attempts')).toBeVisible()
})

test('code challenge explains unavailable remote grading without claiming a score', async ({ page }) => {
  await page.goto('/challenges')
  await page.getByLabel('Challenge type').selectOption('Code')
  await expect(page.getByRole('heading', { name: 'Prepare a Bell pair in code' })).toBeVisible()
  await page.getByRole('link', { name: 'Open code practice' }).click()
  await page.getByLabel('Your solution').fill('h(0)\ncnot(0, 1)')
  await page.getByRole('button', { name: 'Request remote grading' }).click()
  await expect(page.getByText('Remote code grading is unavailable in this frontend demo. No code was executed.')).toBeVisible()
  const recorded = await page.evaluate(() => JSON.parse(localStorage.getItem('learner-progress-storage') ?? '{}').state?.assessmentAttempts ?? [])
  expect(recorded).toHaveLength(0)
})

test('challenge filters narrow the catalog by topic and difficulty', async ({ page }) => {
  await page.goto('/challenges')
  await page.getByLabel('Topic').selectOption('Entanglement')
  await page.getByLabel('Difficulty').selectOption('Intermediate')
  await expect(page.getByRole('heading', { name: 'Build a Bell pair' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Make a balanced qubit' })).toHaveCount(0)
})
