test('Deutsch–Jozsa and Grover circuits produce their distinct target distributions', async ({ page }) => {
  const prepareBuild = async (slug: string) => {
    await page.goto(`/lab/${slug}`)
    await page.getByRole('button', { name: 'Formulate Hypothesis →' }).click()
    await page.getByRole('button', { name: 'Lock Prediction & Arm Simulation Gate' }).click()
  }
  const place = async (gate: string, label: string, qubit: number, step: number) => {
    await page.getByRole('button', { name: `Select ${label} gate` }).click()
    await page.getByRole('button', { name: `Place ${gate} on q${qubit} at step ${step}` }).click()
  }

  await prepareBuild('deutsch-jozsa')
  await place('X', 'Pauli X', 1, 0)
  await place('H', 'Hadamard', 0, 1)
  await place('H', 'Hadamard', 1, 1)
  await place('CNOT', 'Multi-qubit', 0, 3)
  await place('H', 'Hadamard', 0, 4)
  await page.getByRole('button', { name: 'Proceed to Run →' }).click()
  await page.getByRole('button', { name: 'Run Simulation' }).click()
  await page.getByRole('button', { name: 'Statevector', exact: true }).click()
  await expect(page.getByRole('row', { name: /\|01⟩.*50\.00%/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /\|11⟩.*50\.00%/ })).toBeVisible()

  await prepareBuild('grovers')
  await place('H', 'Hadamard', 0, 0)
  await place('H', 'Hadamard', 1, 0)
  await place('CZ', 'Controlled-Z', 0, 1)
  await place('H', 'Hadamard', 0, 2)
  await place('H', 'Hadamard', 1, 2)
  await place('X', 'Pauli X', 0, 3)
  await place('X', 'Pauli X', 1, 3)
  await place('CZ', 'Controlled-Z', 0, 4)
  await place('X', 'Pauli X', 0, 5)
  await place('X', 'Pauli X', 1, 5)
  await place('H', 'Hadamard', 0, 6)
  await place('H', 'Hadamard', 1, 6)
  await page.getByRole('button', { name: 'Proceed to Run →' }).click()
  await page.getByRole('button', { name: 'Run Simulation' }).click()
  await page.getByRole('button', { name: 'Statevector', exact: true }).click()
  await expect(page.getByRole('row', { name: /\|11⟩.*100\.00%/ })).toBeVisible()
})
