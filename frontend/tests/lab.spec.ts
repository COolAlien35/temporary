test('entanglement experiment runs through debug, challenge and mastery', async ({ page }) => {
  await page.goto('/lab/entanglement')
  await expect(page.getByRole('heading', { name: 'Understanding Entanglement' })).toBeVisible()
  await page.getByRole('button', { name: 'Formulate Hypothesis →' }).click()
  await page.getByRole('button', { name: 'Lock Prediction & Arm Simulation Gate' }).click()
  await page.getByRole('button', { name: 'Place H on q0 at step 0' }).click()
  await page.getByRole('button', { name: 'Select Multi-qubit gate' }).click()
  await page.getByRole('button', { name: 'Place CNOT on q0 at step 1' }).click()
  await page.getByRole('button', { name: 'Proceed to Run →' }).click()
  await page.getByRole('button', { name: 'Run Simulation' }).click()
  await page.getByRole('button', { name: 'Discuss with Lab Partner' }).click()
  await page.getByRole('button', { name: 'Proceed to Debug Challenge' }).click()
  await page.getByRole('button', { name: 'Disable X on q1 at step 2' }).click()
  await page.getByRole('button', { name: 'Verify Fix' }).click()
  await expect(page.getByRole('button', { name: 'Fault Isolated ✓' })).toBeVisible()
  await page.getByRole('button', { name: 'Proceed to Challenge' }).click()
  await page.getByRole('button', { name: 'Submit for Scoring' }).click()
  await expect(page.getByRole('button', { name: 'Proceed to Mastery' })).toBeVisible()
  const attempts = await page.evaluate(() => JSON.parse(localStorage.getItem('learner-progress-storage') ?? '{}').state.assessmentAttempts)
  expect(attempts).toEqual(expect.arrayContaining([expect.objectContaining({ kind: 'lab-challenge', assessmentId: 'entanglement', status: 'graded', passed: true })]))
  expect(attempts.find((item: { kind: string }) => item.kind === 'lab-challenge').snapshot.circuit.gates).toHaveLength(2)
  await page.getByRole('button', { name: 'Proceed to Mastery' }).click()
  await expect(page.getByRole('heading', { name: 'Entanglement — Mastered' })).toBeVisible()
})

