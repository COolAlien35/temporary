import { expect, test } from '@playwright/test'

test('lab results follow the built circuit and a rerun replaces stale results', async ({ page }) => {
  await page.goto('/lab/superposition')
  await expect(page.getByRole('heading', { name: 'Understanding Superposition' })).toBeVisible()
  await page.getByRole('button', { name: 'Formulate Hypothesis →' }).click()
  await page.getByRole('button', { name: 'Lock Prediction & Arm Simulation Gate' }).click()
  await page.getByRole('button', { name: 'Place H on q0 at step 0' }).click()
  await page.getByRole('button', { name: 'Proceed to Run →' }).click()
  await page.getByRole('button', { name: 'Run Simulation' }).click()
  await expect(page.getByText(/Latest browser demo result · 1,024 shots/)).toBeVisible()
  await page.getByRole('button', { name: 'Histogram', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Histogram', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Statevector', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Statevector', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Bloch', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Bloch sphere for q[0]' })).toBeVisible()
  const stages = page.getByRole('navigation', { name: 'Lab stages' }).getByRole('button')
  await stages.nth(2).click()
  await stages.nth(4).click()
  await expect(page.getByRole('heading', { name: 'Prediction vs. Actual', exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: /Predicted and sampled outcome frequencies/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /\|00⟩.*%.*%.*pts/ })).toBeVisible()
  await page.getByRole('button', { name: 'Statevector Evolution' }).click()
  await expect(page.getByRole('row', { name: /\|00⟩.*50%/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /\|01⟩.*50%/ })).toBeVisible()

  await stages.nth(2).click()
  await page.getByRole('button', { name: 'Remove H on q0 at step 0' }).click()
  await stages.nth(4).click()
  await expect(page.getByText(/circuit changed after this run/)).toBeVisible()
  await stages.nth(3).click()
  await page.getByRole('button', { name: 'Run Simulation' }).click()
  await stages.nth(4).click()
  await expect(page.getByText(/circuit changed after this run/)).toHaveCount(0)
  await page.getByRole('button', { name: 'Statevector Evolution' }).click()
  await expect(page.getByRole('row', { name: /\|00⟩.*100%/ })).toBeVisible()
  await page.getByRole('button', { name: 'What Changed' }).click()
  await expect(page.getByText('50.0% → 100.0%')).toBeVisible()
  await page.getByRole('button', { name: 'Noise Lab' }).click()
  await page.getByRole('slider', { name: 'Noise strength' }).fill('10')
  await expect(page.getByText(/10% · preview fidelity/)).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Prediction vs. Actual', exact: true })).toBeVisible()
  await expect(page.getByText(/Latest browser demo result · 1,024 shots/)).toBeVisible()
  await expect(page.getByRole('table', { name: /Predicted and sampled outcome frequencies/ })).toBeVisible()

  await page.getByRole('button', { name: 'Discuss with Lab Partner' }).click()
  await page.getByRole('button', { name: 'Proceed to Debug Challenge' }).click()
  await page.getByRole('button', { name: 'Disable X on q1 at step 1' }).click()
  await page.getByRole('button', { name: 'Verify Fix' }).click()
  await expect(page.getByRole('button', { name: 'Fault Isolated ✓' })).toBeVisible()
  await page.getByRole('button', { name: 'Proceed to Challenge' }).click()

  await page.getByRole('button', { name: 'Submit for Scoring' }).click()
  await expect(page.getByText('Optimization Efficiency Score')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Proceed to Mastery' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Place H on q0 at step 0' }).click()
  await page.getByRole('button', { name: 'Submit for Scoring' }).click()
  await page.getByRole('button', { name: 'Proceed to Mastery' }).click()
  await expect(page.getByRole('heading', { name: 'Superposition — Mastered' })).toBeVisible()
})

