import { expect, test } from '@playwright/test'

test('instructor analytics starts empty and unknown learners have recovery', async ({ page }) => {
  await page.goto('/instructor')
  await expect(page.getByText('No local learners yet.')).toBeVisible()
  await page.goto('/instructor/students')
  await expect(page.getByRole('heading', { name: 'No learner profiles yet' })).toBeVisible()
  await page.goto('/instructor/students/unknown')
  await expect(page.getByRole('heading', { name: 'Student not found' })).toBeVisible()
})

test('failed quiz appears in cohort, learner detail and question patterns', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Email').fill('learner@example.edu')
  await page.getByLabel('Password', { exact: true }).fill('demo-pass-123')
  await page.getByRole('button', { name: 'Log in', exact: true }).last().click()
  await expect(page).toHaveURL(/\/home$/)
  await page.goto('/curriculum/u1/quiz')
  await page.getByRole('radio', { name: 'β', exact: true }).check()
  await page.getByRole('radio', { name: '0', exact: true }).check()
  await page.getByRole('radio', { name: 'A relative phase between basis states' }).check()
  await page.getByRole('button', { name: 'Submit quiz' }).click()
  await expect(page.getByText('0/3 correct · 0%')).toBeVisible()

  await page.goto('/instructor')
  await expect(page.getByRole('heading', { name: 'Needs attention' })).toBeVisible()
  await expect(page.getByText('Latest score 0%')).toBeVisible()
  await page.goto('/instructor/students')
  await page.getByLabel('Progress').selectOption('attention')
  await expect(page.getByRole('heading', { name: 'Learner' })).toBeVisible()
  await page.getByLabel('Search students').fill('not-present')
  await expect(page.getByText('No students match these filters.')).toBeVisible()
  await page.getByLabel('Search students').fill('learner')
  await page.getByRole('link', { name: /View detail/ }).click()
  await expect(page.getByRole('heading', { name: 'Assessment history' })).toBeVisible()
  await expect(page.getByText('unit quiz · u1')).toBeVisible()
  await page.goto('/instructor/misconceptions')
  await expect(page.getByRole('heading', { name: 'Question patterns' })).toBeVisible()
  await expect(page.getByText('For |ψ⟩ = α|0⟩ + β|1⟩, what is the probability of measuring 1?')).toBeVisible()
  await expect(page.getByRole('link', { name: 'Related challenge' }).first()).toHaveAttribute('href', '/challenges/balanced-qubit')
})
