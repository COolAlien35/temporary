import { expect, test } from "@playwright/test"
import { runCircuit } from "../lib/sim/run-circuit"
import { inspectedResult } from "../lib/studio/inspection"

// Analytical references check the actual selected state, rather than copying a view implementation.
test("inspection distinguishes intermediate Hadamard state from the final identity state", () => {
  const result = runCircuit(2, [{ id: "h0", type: "H", qubit: 0, step: 0 }, { id: "h1", type: "H", qubit: 0, step: 1 }], { shots: 256 })
  expect(result.probabilities["00"]).toBeCloseTo(1)
  const intermediate = inspectedResult(result, 0)
  expect(intermediate.probabilities["00"]).toBeCloseTo(0.5)
  expect(intermediate.probabilities["01"]).toBeCloseTo(0.5)
  expect(intermediate.blochVectors[0].x).toBeCloseTo(1)
  expect(intermediate.blochVectors[0].z).toBeCloseTo(0)
  expect(inspectedResult(result, 1).blochVectors[0].z).toBeCloseTo(1)
  expect(inspectedResult(result, null)).toBe(result)
  expect(inspectedResult(result, 99)).toBe(result)
})

test("keyboard gate editing and step inspection stay synchronized, preserve zeros, and reject stale steps", async ({ page }) => {
  await page.goto("/studio")
  await page.getByRole("button", { name: "Add gate to sequence" }).focus()
  await page.keyboard.press("Enter")
  await page.keyboard.press("Enter")
  const sequence = page.getByRole("table", { name: "Circuit gate sequence" })
  await expect(sequence.getByRole("button", { name: "Edit H at step 1" })).toBeVisible()
  await page.getByRole("button", { name: "Run", exact: true }).click()
  await page.getByRole("button", { name: "Statevector", exact: true }).click()
  const vector = page.getByRole("table", { name: "Quantum statevector" })
  await expect(vector.locator("tbody tr")).toHaveCount(4)
  await expect(vector.locator("tbody tr").nth(0)).toContainText("100.0%")
  const slider = page.getByRole("slider", { name: "Inspect circuit step" })
  await slider.focus()
  await page.keyboard.press("ArrowLeft")
  await expect(slider).toHaveAttribute("aria-valuetext", "Step 1 of 2, time step 0")
  await expect(page.getByRole("button", { name: "Previous step", exact: true })).toBeDisabled()
  await expect(vector.locator("tbody tr").nth(0)).toContainText("50.0%")
  await expect(vector.locator("tbody tr").nth(1)).toContainText("50.0%")
  await page.getByRole("button", { name: "Bloch", exact: true }).click()
  await expect(page.getByRole("table", { name: "Bloch coordinates" }).locator("tbody tr").first()).toContainText("1.0000.0000.000Pure")
  await slider.focus()
  await page.keyboard.press("ArrowRight")
  await expect(page.getByRole("button", { name: "Next step", exact: true })).toBeDisabled()
  await expect(page.getByRole("table", { name: "Bloch coordinates" }).locator("tbody tr").first()).toContainText("0.0000.0001.000Pure")
  await sequence.getByRole("button", { name: "Delete H at step 0" }).click()
  await expect(sequence.getByRole("button", { name: "Edit H at step 1" })).toBeFocused()
  await expect(page.getByText("Circuit changed. Showing the previous run; rerun to inspect this circuit.")).toBeVisible()
  await expect(slider).toBeDisabled()
  await page.getByRole("button", { name: "Run", exact: true }).click()
  await expect(slider).toBeEnabled()
  await sequence.getByRole("button", { name: "Edit H at step 1" }).click()
  await page.getByRole("spinbutton", { name: "Edit gate step", exact: true }).fill("4")
  await page.getByRole("button", { name: "Save gate changes" }).click()
  await expect(sequence.getByRole("button", { name: "Edit H at step 4" })).toBeFocused()
  await expect(slider).toBeDisabled()
})
