import { expect, test } from '@playwright/test'

test('instructor publishes a circuit quiz, learner answers, instructor responds', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/instructor/assignments')
  await page.getByLabel('Title').fill('Study the Bell state circuit')
  await page.getByLabel('Study instructions').fill('Read the H and CNOT gates, then explain the resulting measurement pattern.')
  await page.getByLabel('Prompt', { exact: true }).fill('Which gate sequence creates a Bell pair?')
  await page.getByLabel('Answer 1').fill('H on q0, then CNOT from q0 to q1')
  await page.getByLabel('Answer 2').fill('X on both qubits')
  await page.getByLabel('Answer 3').fill('Measure both qubits first')
  await page.getByLabel('Answer 4').fill('Z on q0 only')
  await page.getByLabel('Explanation').fill('H creates superposition; CNOT correlates the branches.')
  await page.getByRole('button', { name: 'Add question' }).click()
  const secondQuestion = page.getByRole('group', { name: 'Question 2' })
  await secondQuestion.getByLabel('Prompt', { exact: true }).fill('Which two outcomes should dominate?')
  await secondQuestion.getByLabel('Answer 1').fill('01 and 10')
  await secondQuestion.getByLabel('Answer 2').fill('00 and 11')
  await secondQuestion.getByLabel('Answer 3').fill('Only 01')
  await secondQuestion.getByLabel('Answer 4').fill('All four equally')
  await secondQuestion.getByLabel('Correct answer').selectOption('1')
  await secondQuestion.getByLabel('Explanation').fill('The Bell state correlates 00 and 11.')
  await page.getByLabel('Written response prompt').fill('Why do the measurements agree?')
  await page.getByRole('button', { name: 'Publish assignment' }).click()
  await expect(page.getByRole('status')).toContainText('Assignment published')
  const reviewHref = await page.getByRole('link', { name: 'Review' }).getAttribute('href')
  expect(reviewHref).toMatch(/^\/instructor\/assignments\//)

  await page.goto('/login')
  await page.getByLabel('Email').fill('student@example.edu')
  await page.getByLabel('Password', { exact: true }).fill('demo-pass-123')
  await page.getByRole('button', { name: 'Log in', exact: true }).last().click()
  await expect(page).toHaveURL(/\/home$/)
  await page.goto('/assignments')
  await page.getByRole('link', { name: /Study the Bell state circuit/ }).click()
  await expect(page).toHaveURL(/\/assignments\/[^/]+$/, { timeout: 15000 })
  await expect(page.getByRole('img', { name: 'Bell state circuit diagram' })).toBeVisible({ timeout: 15000 })
  await page.getByRole('button', { name: 'Submit response' }).click()
  await expect(page.getByText('Answer every quiz question before submitting.')).toBeVisible()
  await page.getByRole('radio', { name: 'H on q0, then CNOT from q0 to q1' }).check()
  await page.getByRole('radio', { name: '00 and 11' }).check()
  await page.getByLabel('Written response').fill('The H gate branches q0, and CNOT flips q1 only on the one branch.')
  await page.getByRole('button', { name: 'Save response draft' }).click()
  await page.reload()
  await expect(page.getByRole('radio', { name: 'H on q0, then CNOT from q0 to q1' })).toBeChecked()
  await expect(page.getByRole('radio', { name: '00 and 11' })).toBeChecked()
  await expect(page.getByLabel('Written response')).toHaveValue('The H gate branches q0, and CNOT flips q1 only on the one branch.')
  await page.getByRole('button', { name: 'Submit response' }).click()
  await expect(page.getByRole('status')).toContainText('Response submitted')
  await expect(page.getByText('2/2 quiz answers correct')).toBeVisible()

  await page.goto('/instructor')
  await expect(page.getByText('1 published assignment · 1 response awaiting feedback')).toBeVisible()
  await page.goto(reviewHref!, { waitUntil: 'domcontentloaded', timeout: 30000 })
  await expect(page.getByText('student@example.edu')).toBeVisible({ timeout: 15000 })
  await page.getByLabel('Instructor feedback').fill('Good explanation. Now compare the 00 and 11 outcomes in Studio.')
  await page.getByRole('button', { name: 'Save feedback' }).click()
  await expect(page.getByRole('status')).toContainText('Visible to this learner')
  await page.goto('/instructor')
  await expect(page.getByText('1 published assignment · 0 responses awaiting feedback')).toBeVisible()
  await page.goto('/assignments')
  await page.getByRole('link', { name: /Study the Bell state circuit/ }).click()
  await expect(page.getByText('Good explanation. Now compare the 00 and 11 outcomes in Studio.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Good explanation. Now compare the 00 and 11 outcomes in Studio.')).toBeVisible()
})

test('targeted work stays private to the selected demo profile and published versions stay fixed', async ({ page }) => {
  await page.goto('/studio?template=superposition')
  await expect(page.getByRole('button', { name: 'Superposition', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save circuit' }).click()
  await page.goto('/instructor/assignments')
  await page.getByLabel('Circuit for learners to study').selectOption({ label: 'Saved: Superposition' })
  await page.getByLabel('Title').fill('Read the superposition circuit')
  await page.getByLabel('Study instructions').fill('Study the Hadamard gate before choosing an answer.')
  await page.getByLabel('Prompt', { exact: true }).fill('What does H do to |0⟩?')
  await page.getByLabel('Answer 1').fill('Creates equal amplitudes')
  await page.getByLabel('Answer 2').fill('Measures the qubit')
  await page.getByLabel('Answer 3').fill('Deletes the state')
  await page.getByLabel('Answer 4').fill('Always creates |1⟩')
  await page.getByLabel('Explanation').fill('H maps |0⟩ to an equal superposition.')
  await page.getByLabel('Written response prompt').fill('Describe the expected histogram.')
  await page.getByLabel('Assign to').selectOption('email')
  await page.getByLabel('Learner email').fill('chosen@example.edu')
  await page.getByRole('button', { name: 'Publish assignment' }).click()
  await page.getByRole('button', { name: 'New version' }).click()
  await expect(page.getByLabel('Title')).toHaveValue('Read the superposition circuit')
  await page.getByLabel('Title').fill('Read the revised superposition circuit')
  await page.getByRole('button', { name: 'Save draft' }).click()
  await expect(page.getByText('Read the revised superposition circuit')).toBeVisible()

  async function signIn(email: string) {
    await page.goto('/login')
    await page.getByLabel('Email').fill(email)
    await page.getByLabel('Password', { exact: true }).fill('demo-pass-123')
    await page.getByRole('button', { name: 'Log in', exact: true }).last().click()
    await expect(page).toHaveURL(/\/home$/)
  }

  await signIn('other@example.edu')
  await page.goto('/assignments')
  await expect(page.getByText('Nothing assigned yet')).toBeVisible()
  await page.getByRole('button', { name: 'Log out' }).click()
  await signIn('chosen@example.edu')
  await page.goto('/assignments')
  await expect(page.getByRole('link', { name: /Read the superposition circuit/ })).toBeVisible()
  await expect(page.getByText('Read the revised superposition circuit')).toHaveCount(0)
})
