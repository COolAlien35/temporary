import { expect, test } from '@playwright/test'

test('contest entry attaches a graded circuit and unknown contests recover', async ({ page }) => {
  await page.goto('/contests/not-a-contest')
  await expect(page.getByRole('heading', { name: 'Contest not found' })).toBeVisible()
  await page.goto('/contests/noise-navigator')
  await expect(page.getByText('Graded entry needs a noise service.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Enter demo contest' })).toHaveCount(0)
  await page.goto('/contests/entanglement-speed')
  await page.getByRole('button', { name: 'Enter demo contest' }).click()
  await expect(page.getByRole('heading', { name: 'Your contest submissions' })).toBeVisible()
  await page.getByRole('link', { name: 'Start contest challenge' }).click()
  await expect(page.getByText('This submission will be attached to your browser-local contest entry.')).toBeVisible()
  await page.getByRole('button', { name: 'H', exact: true }).click()
  await page.getByRole('button', { name: 'CNOT', exact: true }).click()
  await page.getByRole('button', { name: 'Submit attempt' }).click()
  await expect(page.getByText('Passed')).toBeVisible()
  await page.getByRole('link', { name: 'View contest result' }).click()
  await page.getByRole('button', { name: 'View your submissions' }).click()
  await expect(page.getByRole('link', { name: /100% · Review/ })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'View your submissions' }).click()
  await expect(page.getByRole('link', { name: /100% · Review/ })).toBeVisible()
  await page.getByRole('tab', { name: 'Leaderboard' }).click()
  await expect(page.getByText('Demo Explorer · You')).toBeVisible()
})

test('thread, reply and vote persist; contest discussions stay in their contest', async ({ page }) => {
  await page.goto('/discussions/unknown')
  await expect(page.getByRole('heading', { name: 'Thread not found' })).toBeVisible()
  await page.goto('/discussions')
  await page.getByRole('button', { name: 'New Thread' }).click()
  const dialog = page.getByRole('dialog', { name: 'Create a discussion thread' })
  await dialog.getByLabel('Title').fill('Why do Bell outcomes match?')
  await dialog.getByLabel('Post').fill('I can build the circuit, but I want to understand why the two measurement results match.')
  await dialog.getByRole('button', { name: 'Publish thread' }).click()
  await expect(page).toHaveURL(/\/discussions\/[^/]+$/)
  await page.getByLabel('Your response').fill('CNOT correlates the target with the control branch.')
  await page.getByRole('button', { name: 'Post reply' }).click()
  await expect(page.getByText('CNOT correlates the target with the control branch.')).toBeVisible()
  await page.getByRole('button', { name: /Upvote/ }).click()
  await expect(page.getByRole('button', { name: /Remove vote/ })).toBeVisible()
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('quantumloop-demo-community') ?? '{}').state)
  expect(stored.replies).toHaveLength(1)
  expect(Object.values(stored.votes)).toContainEqual(['demo-learner'])
  await page.reload()
  await expect(page.getByText('CNOT correlates the target with the control branch.')).toBeVisible()
  await expect(page.getByRole('button', { name: /Remove vote/ })).toBeVisible()
  await page.goto('/discussions')
  await page.getByRole('button', { name: 'New', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Why do Bell outcomes match?' })).toBeVisible()

  await page.goto('/contests/entanglement-speed')
  await page.getByRole('tab', { name: 'Discussion' }).click()
  await page.getByRole('button', { name: 'New Thread' }).click()
  const contestDialog = page.getByRole('dialog', { name: 'Create a discussion thread' })
  await contestDialog.getByLabel('Title').fill('Bell-pair gate order')
  await contestDialog.getByLabel('Post').fill('I am comparing H then CNOT with the reverse order in this contest.')
  await contestDialog.getByRole('button', { name: 'Publish thread' }).click()
  await expect(page.getByRole('link', { name: 'Entanglement Speed Challenge' }).first()).toHaveAttribute('href', '/contests/entanglement-speed')
  await page.goto('/contests/entanglement-speed')
  await page.getByRole('tab', { name: 'Discussion' }).click()
  await expect(page.getByRole('link', { name: 'Bell-pair gate order' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Why do Bell outcomes match?' })).toHaveCount(0)
})

test('leaderboard scope and time controls change the ranked dataset', async ({ page }) => {
  await page.goto('/leaderboard')
  await expect(page.getByRole('button', { name: 'global' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'contest' }).click()
  await page.getByLabel('Contest').selectOption('measurement-lab')
  await page.getByRole('button', { name: 'This week' }).click()
  await expect(page.getByText('No rankings for this selection yet.')).toBeVisible()
  await page.getByRole('button', { name: 'All time' }).click()
  await expect(page.getByText('No rankings for this selection yet.')).toHaveCount(0)
  await page.getByRole('button', { name: 'Learning module' }).click()
  await page.getByLabel('Module').selectOption('u3')
  await expect(page.getByRole('button', { name: 'Learning module' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByText('Sample').first()).toBeVisible()
})
